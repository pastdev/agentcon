#!/bin/bash
# Install golangci-lint and drop a profile fragment for container startup.

set -euo pipefail

# shellcheck source=lib/cache.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/cache.sh"

readonly GOLANGCI_LINT_VERSION="${GOLANGCI_LINT_VERSION:-v2.13.2}"
readonly GOLANGCI_LINT_BIN_DIR="${GOLANGCI_LINT_BIN_DIR:-/usr/local/bin}"
readonly PROFILE_DIR="${PROFILE_DIR:-/etc/profile.d}"
readonly PROFILE_FILE="${PROFILE_DIR}/golangci_lint.sh"

function install_binary {
  local arch checksums checksums_url go_arch name release_base
  local sha tarball tarball_url version

  arch="$(uname -m)"
  case "${arch}" in
    aarch64)
      go_arch=arm64
      ;;
    x86_64)
      go_arch=amd64
      ;;
    *)
      echo "unsupported arch ${arch}" >&2
      return 1
      ;;
  esac

  version="${GOLANGCI_LINT_VERSION#v}"
  name="golangci-lint-${version}-linux-${go_arch}"
  release_base="https://github.com/golangci/golangci-lint/releases/download"
  checksums_url="${release_base}/${GOLANGCI_LINT_VERSION}"
  checksums_url="${checksums_url}/golangci-lint-${version}-checksums.txt"
  tarball_url="${release_base}/${GOLANGCI_LINT_VERSION}/${name}.tar.gz"
  checksums="$(cache_fetch "${checksums_url}")"
  sha="$(awk -v file="${name}.tar.gz" \
    '$2 == file { print $1; exit }' "${checksums}")"
  if [[ -z "${sha}" ]]; then
    echo "no checksum for ${name}.tar.gz" >&2
    return 1
  fi
  tarball="$(cache_fetch "${tarball_url}" "${sha}")"

  tar --directory /tmp --extract --gzip --file "${tarball}" \
    "${name}/golangci-lint"
  install --mode 0755 \
    "/tmp/${name}/golangci-lint" \
    "${GOLANGCI_LINT_BIN_DIR}/golangci-lint"
  rm --recursive --force "/tmp/${name}"
}

function write_profile {
  mkdir --parents "${PROFILE_DIR}"
  cat >"${PROFILE_FILE}" <<EOF
# Generated by install_golangci_lint.sh
export PATH="${GOLANGCI_LINT_BIN_DIR}:\${PATH}"
EOF
}

function main {
  install_binary
  write_profile
}

main "$@"
