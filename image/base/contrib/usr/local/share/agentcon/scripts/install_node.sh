#!/bin/bash
# Install the Node.js toolchain and drop a profile fragment for container startup.

set -euo pipefail

# shellcheck source=lib/cache.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/cache.sh"

readonly NODE_VERSION="${NODE_VERSION:-24.21.0}"
readonly NODE_PREFIX="${NODE_PREFIX:-/usr/local/node}"
readonly PROFILE_DIR="${PROFILE_DIR:-/etc/profile.d}"
readonly PROFILE_FILE="${PROFILE_DIR}/node.sh"

function install_tarball {
  local arch node_arch node_sha node_url tarball

  arch="$(uname -m)"
  case "${arch}" in
    aarch64)
      node_arch=linux-arm64
      node_sha=724282c3b43aec998aa9527380465b45d229e021b58035f5f4f63095eabfe5d5
      ;;
    x86_64)
      node_arch=linux-x64
      node_sha=6e1db87ef58b8819e5d5402eff1536491b18edd8eb7bee5ef7897876e88dc5ff
      ;;
    *)
      echo "unsupported arch ${arch}" >&2
      return 1
      ;;
  esac

  node_url="https://nodejs.org/dist/v${NODE_VERSION}/node-v${NODE_VERSION}-${node_arch}.tar.gz"
  tarball="$(cache_fetch "${node_url}" "${node_sha}")"
  rm --recursive --force "${NODE_PREFIX}"
  mkdir --parents "${NODE_PREFIX}"
  tar --directory "${NODE_PREFIX}" --strip-components=1 \
    --extract --gzip --file "${tarball}"
}

function write_profile {
  mkdir --parents "${PROFILE_DIR}"
  cat >"${PROFILE_FILE}" <<EOF
# Generated by install_node.sh
export PATH="${NODE_PREFIX}/bin:\${PATH}"
EOF
}

function main {
  install_tarball
  write_profile
}

main "$@"
