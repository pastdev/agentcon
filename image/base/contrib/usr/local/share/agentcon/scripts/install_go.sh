#!/bin/bash
# Install the Go toolchain and drop a profile fragment for container startup.

set -euo pipefail

# shellcheck source=lib/cache.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/cache.sh"

readonly GO_VERSION="${GO_VERSION:-1.27.1}"
readonly GO_PREFIX="${GO_PREFIX:-/usr/local/go}"
readonly PROFILE_DIR="${PROFILE_DIR:-/etc/profile.d}"
readonly PROFILE_FILE="${PROFILE_DIR}/go.sh"

function install_tarball {
  local arch go_arch go_sha go_url tarball

  arch="$(uname -m)"
  case "${arch}" in
    aarch64)
      go_arch=arm64
      go_sha=3450b45a3f9ee8568792736a5c5e70a1f2e9b36c35a8f74958c03e51d7d92bec
      ;;
    x86_64)
      go_arch=amd64
      go_sha=63d339f0da5ab53635a56f2490a7984dfe12dfcff22ad749f63edaf590168445
      ;;
    *)
      echo "unsupported arch ${arch}" >&2
      return 1
      ;;
  esac

  go_url="https://go.dev/dl/go${GO_VERSION}.linux-${go_arch}.tar.gz"
  tarball="$(cache_fetch "${go_url}" "${go_sha}")"
  rm --recursive --force "${GO_PREFIX}"
  tar --directory "$(dirname "${GO_PREFIX}")" \
    --extract --gzip --file "${tarball}"
}

function write_profile {
  mkdir --parents "${PROFILE_DIR}"
  cat >"${PROFILE_FILE}" <<EOF
# Generated by install_go.sh
export GOROOT="${GO_PREFIX}"
export GOTOOLCHAIN=local
export PATH="\${GOROOT}/bin:\${PATH}"
EOF
}

function main {
  install_tarball
  write_profile
}

main "$@"
